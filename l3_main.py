a=input('Добрый день! Введите имя, по которому к Вам можно обратиться:')
b=int(input(f'Добрый день, {a}! Введите Ваш возраст, и я посчитаю, сколько Вам осталось до пенсии в годах:'))
if b>=63:
    print('Вы уже на своей заслуженной пенсии!')
elif b<0:
    print('Введите корректный возраст!')
else:
    print(f'Вам до пенсии осталось: {63-b} лет. Всего доброго.')